export const LANGUAGES = Object.keys(dict);

export function currentLang() {
  const { lang } = getSettings();
  if (lang && dict[lang]) return lang;
  const device = (navigator.language || 'en').slice(0, 2);
  return dict[device] ? device : 'en';
}

export function t(key, vars = {}) {
  const s = dict[currentLang()][key] ?? dict.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

export function formatDate(iso) {
  return new Date(iso).toLocaleString(currentLang(), { dateStyle: 'medium', timeStyle: 'short' });
}
